// Every piece of on-screen text goes through tr("..."), and every tr() string is listed in
// src/locale/en_US/translations.ts, Roku's catalog for that language (the base for others).
// `node scripts/check-strings.mjs` fails when the catalog is out of date; `--write` rewrites it.
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const files = [];
const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else if (/\.(bs|brs)$/.test(name)) files.push(p);
  }
};
walk('src/source');
walk('src/components');

const strings = new Set();
for (const f of files) {
  for (const m of readFileSync(f, 'utf8').matchAll(/\btr\("((?:[^"]|"")*)"\)/g)) strings.add(m[1].replace(/""/g, '"'));
}
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const sorted = [...strings].sort((a, b) => a.localeCompare(b));
const xml = `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE TS>
<!-- Generated by scripts/check-strings.mjs from the app's tr() calls. -->
<TS version="2.0" language="en_US" sourcelanguage="en_US">
<context>
<name>default</name>
${sorted.map((s) => `<message>\n  <source>${esc(s)}</source>\n  <translation>${esc(s)}</translation>\n</message>`).join('\n')}
</context>
</TS>
`;
const path = 'src/locale/en_US/translations.ts';
if (process.argv.includes('--write')) {
  writeFileSync(path, xml);
  console.log(`${sorted.length} strings written to ${path}`);
} else {
  let current = '';
  try { current = readFileSync(path, 'utf8'); } catch {}
  if (current !== xml) {
    console.error(`${path} is out of date: run node scripts/check-strings.mjs --write`);
    process.exit(1);
  }
  console.log(`${sorted.length} strings, catalog up to date`);
}
